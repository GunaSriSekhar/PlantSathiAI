import React, { useState, useEffect, useRef } from 'react';
import { useSearchParams, Link } from 'react-router-dom';
import {
  Bot,
  Send,
  User,
  Sparkles,
  HelpCircle,
  AlertCircle,
  ArrowRight,
  ShieldAlert,
} from 'lucide-react';
import { Card, CardHeader, CardTitle, CardContent } from '../components/ui/Card';
import { Button } from '../components/ui/Button';
import { Badge } from '../components/ui/Badge';
import { chatWithDoctor } from '../services/api';
import { ChatMessage, ChatResponse } from '../types';

export const AiDoctor: React.FC = () => {
  const [searchParams] = useSearchParams();
  const scanId = searchParams.get('scan_id') || undefined;

  const [messages, setMessages] = useState<ChatMessage[]>([
    {
      role: 'assistant',
      content:
        "Hello! I am your PlantSathi AI Care Assistant. I can help answer questions regarding watering protocols, sunlight needs, soil management, pest control, and disease prevention. What would you like to know about your plants?",
    },
  ]);
  const [input, setInput] = useState('');
  const [loading, setLoading] = useState(false);
  const [suggestions, setSuggestions] = useState<string[]>([
    'How do I treat tomato early blight?',
    'What are the watering rules for peppers?',
    'How to prevent powdery mildew?',
    'Signs of overwatering vs underwatering?',
  ]);
  const messagesEndRef = useRef<HTMLDivElement>(null);

  useEffect(() => {
    messagesEndRef.current?.scrollIntoView({ behavior: 'smooth' });
  }, [messages]);

  const handleSend = async (messageToSend?: string) => {
    const text = (messageToSend || input).trim();
    if (!text || loading) return;

    setInput('');
    const newHistory: ChatMessage[] = [...messages, { role: 'user', content: text }];
    setMessages(newHistory);
    setLoading(true);

    try {
      const response = await chatWithDoctor(text, scanId, newHistory);
      setMessages((prev) => [...prev, { role: 'assistant', content: response.message }]);
      if (response.suggestions && response.suggestions.length > 0) {
        setSuggestions(response.suggestions);
      }
    } catch (err) {
      setMessages((prev) => [
        ...prev,
        {
          role: 'assistant',
          content: 'Sorry, I encountered an error retrieving care guidance. Please make sure the backend is reachable.',
        },
      ]);
    } finally {
      setLoading(false);
    }
  };

  return (
    <div className="max-w-3xl mx-auto space-y-6">
      {/* Title */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3">
        <div>
          <h1 className="text-2xl font-bold text-gray-900 tracking-tight flex items-center gap-2">
            <Bot className="w-6 h-6 text-primary-700" />
            <span>AI Plant Doctor</span>
          </h1>
          <p className="text-xs text-gray-500 mt-0.5">
            Rule-based agronomic expert system trained on plant pathology fundamentals.
          </p>
        </div>
        {scanId && (
          <Badge variant="info" size="sm">
            Context: Scan {scanId.slice(0, 8)}...
          </Badge>
        )}
      </div>

      {/* Transparency Banner */}
      <div className="p-3.5 rounded-xl bg-blue-50/70 border border-blue-200/70 text-xs text-blue-900 flex items-start gap-2.5">
        <HelpCircle className="w-4 h-4 text-blue-600 flex-shrink-0 mt-0.5" />
        <p className="leading-relaxed">
          <span className="font-semibold">Notice:</span> Responses are generated by a deterministic,
          evidence-based expert rule engine. This platform does not simulate fake LLM chat or generate unverified advice.
        </p>
      </div>

      {/* Chat Area */}
      <Card className="h-[520px] flex flex-col p-0 overflow-hidden border border-gray-100 shadow-soft">
        {/* Messages Stream */}
        <div className="flex-1 p-5 overflow-y-auto space-y-4">
          {messages.map((msg, index) => (
            <div
              key={index}
              className={`flex gap-3 max-w-[85%] ${
                msg.role === 'user' ? 'ml-auto flex-row-reverse' : ''
              }`}
            >
              <div
                className={`w-8 h-8 rounded-full flex items-center justify-center flex-shrink-0 text-white ${
                  msg.role === 'user' ? 'bg-primary-800' : 'bg-primary-600'
                }`}
              >
                {msg.role === 'user' ? <User className="w-4 h-4" /> : <Bot className="w-4 h-4" />}
              </div>

              <div
                className={`p-4 rounded-2xl text-xs sm:text-sm leading-relaxed whitespace-pre-wrap ${
                  msg.role === 'user'
                    ? 'bg-primary-700 text-white rounded-tr-none'
                    : 'bg-gray-50 text-gray-800 border border-gray-100 rounded-tl-none'
                }`}
              >
                {msg.content}
              </div>
            </div>
          ))}
          {loading && (
            <div className="flex gap-3 max-w-[85%]">
              <div className="w-8 h-8 rounded-full bg-primary-600 flex items-center justify-center text-white">
                <Bot className="w-4 h-4" />
              </div>
              <div className="p-4 rounded-2xl bg-gray-50 border border-gray-100 rounded-tl-none text-xs text-gray-400 animate-pulse">
                Consulting plant care guidelines...
              </div>
            </div>
          )}
          <div ref={messagesEndRef} />
        </div>

        {/* Suggested Queries */}
        {suggestions.length > 0 && (
          <div className="px-5 py-2.5 bg-gray-50/70 border-t border-gray-100 flex items-center gap-2 overflow-x-auto">
            <span className="text-[11px] font-semibold text-gray-400 uppercase tracking-wider flex-shrink-0">
              Suggestions:
            </span>
            {suggestions.map((s, idx) => (
              <button
                key={idx}
                onClick={() => handleSend(s)}
                className="text-xs bg-white border border-gray-200 hover:border-primary-400 hover:text-primary-800 text-gray-600 px-3 py-1 rounded-full whitespace-nowrap transition-colors"
              >
                {s}
              </button>
            ))}
          </div>
        )}

        {/* Input Bar */}
        <div className="p-4 border-t border-gray-100 bg-white">
          <form
            onSubmit={(e) => {
              e.preventDefault();
              handleSend();
            }}
            className="flex items-center gap-2"
          >
            <input
              type="text"
              value={input}
              onChange={(e) => setInput(e.target.value)}
              placeholder="Ask about watering, sunlight, soil, disease prevention..."
              className="flex-1 px-4 py-2.5 text-sm bg-gray-50 border border-gray-200 rounded-xl focus:outline-none focus:ring-2 focus:ring-primary-500/20 focus:border-primary-600 transition-colors"
              disabled={loading}
            />
            <Button
              type="submit"
              variant="primary"
              size="md"
              disabled={!input.trim() || loading}
              icon={<Send className="w-4 h-4" />}
            >
              Send
            </Button>
          </form>
        </div>
      </Card>

      {/* Advisory Footer */}
      <div className="flex items-center justify-center gap-2 text-[11px] text-gray-400 text-center">
        <ShieldAlert className="w-3.5 h-3.5" />
        <span>For severe agricultural epidemics, verify with an agronomist or local university extension service.</span>
      </div>
    </div>
  );
};
